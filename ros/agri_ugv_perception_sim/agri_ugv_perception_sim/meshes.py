"""Wavefront OBJ meshes with texture coordinates: writing them for Gazebo, reading them back."""

import numpy as np


def obj_text(vertices, uvs, faces, normals):
    """
    Return a mesh as OBJ text: positions in mm, texture coordinates to 5 decimals.

    The texture coordinates are finer than agri_ugv_field's (3 decimals) because the weed
    stickers show small parts of one large texture (stickers.atlas): 5 decimals keep them
    within a hundredth of a pixel there.
    """
    lines = ['# Generated by agri_ugv_perception_sim']
    lines += [f'v {x:.3f} {y:.3f} {z:.3f}' for x, y, z in vertices]
    lines += [f'vt {a:.5f} {b:.5f}' for a, b in uvs]
    lines += [f'vn {x:.2f} {y:.2f} {z:.2f}' for x, y, z in normals]
    lines += [f'f {i}/{i}/{i} {j}/{j}/{j} {k}/{k}/{k}' for i, j, k in np.asarray(faces) + 1]
    return '\n'.join(lines) + '\n'


def read_obj(text):
    """
    Return (vertices, uvs, faces) of OBJ text as obj_text writes it.

    Each face corner must name the same index for its position and its texture coordinate
    (f i/i/i ...), as agri_ugv_field and obj_text write them.
    """
    vertices, uvs, faces = [], [], []
    for line in text.splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] == 'v':
            vertices.append([float(v) for v in parts[1:4]])
        elif parts[0] == 'vt':
            uvs.append([float(v) for v in parts[1:3]])
        elif parts[0] == 'f':
            corners = [p.split('/') for p in parts[1:4]]
            if any(len(c) < 2 or c[0] != c[1] for c in corners):
                raise ValueError(f'face {line!r}: position and texture index differ')
            faces.append([int(c[0]) - 1 for c in corners])
    return (np.array(vertices, dtype=float).reshape(-1, 3),
            np.array(uvs, dtype=float).reshape(-1, 2),
            np.array(faces, dtype=int).reshape(-1, 3))
